import * as XLSX from 'xlsx';
import { SheetData, ExcelData, DataRow } from '../types';

export function parseExcelFile(file: File): Promise<ExcelData> {
  return new Promise((resolve, reject) => {
    const reader = new FileReader();
    reader.onload = (e) => {
      try {
        const data = e.target?.result;
        const workbook = XLSX.read(data, { type: 'array' });
        
        const sheets: SheetData[] = workbook.SheetNames.map(sheetName => {
          const worksheet = workbook.Sheets[sheetName];
          const jsonData = XLSX.utils.sheet_to_json(worksheet, { header: 1 }) as any[][];
          
          return parseSheet(sheetName, jsonData);
        });

        resolve({
          sheets,
          lastUpdated: new Date(),
          fileName: file.name
        });
      } catch (error) {
        reject(error);
      }
    };
    reader.onerror = reject;
    reader.readAsArrayBuffer(file);
  });
}

function parseSheet(name: string, rawData: any[][]): SheetData {
  if (rawData.length < 2) {
    return {
      name,
      headers: [],
      multiLevelHeaders: [],
      rows: [],
      textColumns: [],
      numericColumns: []
    };
  }

  // Detect multi-level headers
  let headerRowCount = 1;
  const multiLevelHeaders: string[][] = [];
  
  // Check if first few rows are headers (contain mostly text, few numbers)
  for (let i = 0; i < Math.min(5, rawData.length); i++) {
    const row = rawData[i];
    const numericCount = row.filter(cell => typeof cell === 'number').length;
    const textCount = row.filter(cell => typeof cell === 'string' && cell.trim()).length;
    
    if (textCount > numericCount && textCount > 0) {
      multiLevelHeaders.push(row.map(cell => String(cell || '')));
      headerRowCount = i + 1;
    } else {
      break;
    }
  }

  // Use last header row as primary headers
  const headers = multiLevelHeaders.length > 0 
    ? multiLevelHeaders[multiLevelHeaders.length - 1]
    : rawData[0].map(cell => String(cell || `Column_${rawData[0].indexOf(cell)}`));

  // Parse data rows
  const dataRows: DataRow[] = [];
  for (let i = headerRowCount; i < rawData.length; i++) {
    const row = rawData[i];
    if (row.some(cell => cell !== null && cell !== undefined && cell !== '')) {
      const dataRow: DataRow = {};
      headers.forEach((header, idx) => {
        dataRow[header] = row[idx] !== undefined ? row[idx] : '';
      });
      dataRows.push(dataRow);
    }
  }

  // Classify columns
  const textColumns: string[] = [];
  const numericColumns: string[] = [];

  headers.forEach(header => {
    const values = dataRows.map(row => row[header]).filter(v => v !== '' && v !== null && v !== undefined);
    const numericValues = values.filter(v => typeof v === 'number' || (!isNaN(Number(v)) && String(v).trim() !== ''));
    
    if (numericValues.length > values.length * 0.7 && numericValues.length > 0) {
      numericColumns.push(header);
    } else if (values.length > 0) {
      textColumns.push(header);
    }
  });

  return {
    name,
    headers,
    multiLevelHeaders,
    rows: dataRows,
    textColumns,
    numericColumns
  };
}

